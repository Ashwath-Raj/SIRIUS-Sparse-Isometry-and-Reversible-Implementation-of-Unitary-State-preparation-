#!/usr/bin/env bash
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [[ -z "$ROOT" ]]; then
  echo "ERROR: run this from somewhere inside the project Git repository." >&2
  exit 2
fi
cd "$ROOT"

PHASE2="$ROOT/results/raw/phase2"
NOTES="$ROOT/research-notes"
mkdir -p "$PHASE2" "$NOTES"

# Preserve the earlier interrupted full-suite run and the isolated diagnostic.
if [[ -f "$PHASE2/python_pytest.log" ]]; then
  cp "$PHASE2/python_pytest.log" "$PHASE2/python_initial_run_57_passed_then_interrupted.log"
fi
if [[ -f /tmp/sparse-test58.log ]]; then
  cp /tmp/sparse-test58.log "$PHASE2/python_test58_diagnostic.log"
fi
if [[ -f /tmp/sparse-state-test-list.txt ]]; then
  cp /tmp/sparse-state-test-list.txt "$PHASE2/python_collected_test_ids.txt"
fi

cat > "$PHASE2/python_remaining_segment_operator_record.log" <<'LOG'
Operator-provided pytest output transcript (not a fresh rerun).
Selection: collected test IDs 59 through 150, excluding test_bloq_phases[bloq_ex1] at position 58.
Result: 89 passed, 3 skipped in 69.24s (0:01:09).
Exit code: 0.
The three skips were QDType incompatibilities reported by the upstream bloq autotester:
- uncompute_test.py::test_example[qtyping-bloq_ex1]
- uncompute_test.py::test_example[qtyping-bloq_ex2]
- uncompute_test.py::test_example[qtyping-bloq_ex3]
The command and complete terminal output were supplied in the conversation on 2026-11-14.
LOG

cat > "$NOTES/PHASE2_VALIDATION_RECORD.md" <<'MD'
# Phase 2 — Official reference validation record

**Status:** validated with one documented resource-limited upstream stress test; not a fully green 150/150 pytest run.

## Environment and source integrity

- Official Zenodo artifact MD5 matched the expected value: `c58634ba415b4e3fb729648460f32ad7`.
- `uv sync --frozen` completed successfully (exit code 0).
- `Cargo.lock` and `uv.lock` remained unchanged throughout the audit.
- The locked dependency check found no `nbconvert` package.
- Rust toolchain: `rustc 1.100.0`, `cargo 1.100.0`.

## Tests

| Suite | Result | Notes |
|---|---:|---|
| Rust | 30 passed, 0 failed | `cargo test --locked`, exit 0 |
| Python first segment | 57 passed | Original full run was interrupted while executing the next test |
| Python remaining segment | 89 passed, 3 skipped | 92 selected tests; 69.24 seconds; exit 0 |
| Python test 58 | Resource-limited / unverified | `test_bloq_phases[bloq_ex1]` exceeded diagnostic time limits |

Aggregate Python accounting: **146 passed, 3 skipped, 1 unverified** out of 150 collected tests.

The three skips were emitted by the upstream test helper for Qualtran QDType incompatibilities in the `uncompute_test.py` qtyping examples. They were not assertion failures.

## Unverified upstream stress test

Test node: `src/sparse_state_preparation/isometry_test.py::test_bloq_phases[bloq_ex1]`.

Its fixture is `_isometry_to_subspace_with_phase_big()`, which constructs `IsometryToSubspaceViaBatching(random_tableau(540, 30), random_signs(540), 2)`. The test iterates over the isometry bijection and calls `do_phased_classical_simulation`. The captured Python stack showed time spent in Qualtran composite-Bloq connection/finalization and recursive classical simulation. A three-minute isolated diagnostic timed out; no assertion failure was observed.

This test is **not marked passed or skipped**. It remains unverified on the RTX 3050 laptop and may be revisited on a stronger CPU/HPC environment if its result becomes necessary.

## Decision and limitations

Phase 2 is accepted as a sufficiently validated reference baseline to begin Phase 3. The full upstream Python suite is not claimed to be completely green. The authors' source and lockfiles were not modified. This record does not change the upstream test selection or its expected behaviour.

## Evidence files

- `results/raw/phase2/PHASE2_SUMMARY.txt` — original audit summary (captures the first interrupted run; its Python exit code 2 is expected from KeyboardInterrupt).
- `results/raw/phase2/python_initial_run_57_passed_then_interrupted.log` — first-run pytest output.
- `results/raw/phase2/python_test58_diagnostic.log` — faulthandler stack from the isolated diagnostic, when copied from `/tmp`.
- `results/raw/phase2/python_remaining_segment_operator_record.log` — operator-provided result summary for the remaining 92 tests (the terminal transcript was supplied in the conversation).
- `results/raw/phase2/python_collected_test_ids.txt` — collected test node IDs, when copied from `/tmp`.
- `research-notes/REFERENCE_CODE_MAP.md` — preliminary structural map generated by the audit script; review it before relying on function-level claims.

No remote operation is authorized. Do not push.
MD

# Add a compact machine-readable roll-up without overwriting the raw audit result.
cat > "$PHASE2/PHASE2_CONSOLIDATED_STATUS.txt" <<'STATUS'
Phase 2 consolidated status (2026-11-14)
Official archive checksum: PASS
uv sync --frozen: PASS (exit 0)
Rust: 30 passed, 0 failed (cargo test --locked, exit 0)
Python: 146 passed, 3 skipped, 1 unverified (150 collected)
Unverified: isometry_test.py::test_bloq_phases[bloq_ex1] (large 540x30 phase-simulation fixture; diagnostic timeout)
Lockfile integrity: PASS; no source/lockfile modifications
Decision: proceed to Phase 3 with the unverified stress test explicitly documented.
STATUS

printf '%s\n' 'Phase 2 closeout files created:' 
printf '  %s\n' "$NOTES/PHASE2_VALIDATION_RECORD.md" "$PHASE2/PHASE2_CONSOLIDATED_STATUS.txt"
printf '%s\n' 'Evidence copies:'
for f in \
  "$PHASE2/python_initial_run_57_passed_then_interrupted.log" \
  "$PHASE2/python_test58_diagnostic.log" \
  "$PHASE2/python_collected_test_ids.txt"; do
  [[ -f "$f" ]] && printf '  PRESENT  %s\n' "$f" || printf '  NOT COPIED (source was absent)  %s\n' "$f"
done

git diff --check
printf '\nGit status (no commit made):\n'
git status --short --branch
